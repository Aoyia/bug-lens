import { strToU8 } from "fflate";

import type {
  ConsoleEntry,
  InteractionRecord,
  IssueScene,
  NetworkEntry,
  RecordingSession,
} from "../shared/protocol";
import { getLocale, isEn } from "../shared/i18n.ts";
import zhCnMessages from "../_locales/zh_CN/messages.json" with { type: "json" };
